import assert from "node:assert/strict";
import { changeQueryMode, stepConfigValidationError } from "../frontend/components/step-editor/step-config";
const sql = { query: "SELECT 1", storeAs: "customer", params: [1], single: true, required: false, customOption: "preserve" };
const resolve = changeQueryMode(sql, "resolveContactCustomer");
assert.deepEqual(resolve, { operation: "resolveContactCustomer", storeAs: "customerResolution", customOption: "preserve" });
assert.equal(stepConfigValidationError("QUERY", resolve), null, "resolver mode saves without SQL");
assert.equal(sql.query, "SELECT 1", "mode edits do not mutate the original configuration");
const back = changeQueryMode(resolve, "sql");
assert.equal(back["operation"], undefined);
assert.equal(back["customOption"], "preserve");
assert.ok(stepConfigValidationError("QUERY", back), "SQL mode still requires SQL");
assert.equal(stepConfigValidationError("QUERY", { ...back, query: "SELECT 1" }), null);
for (const name of ["contact", "message", "a.b", "__proto__", "", "constructor"]) assert.ok(stepConfigValidationError("QUERY", { operation: "resolveContactCustomer", storeAs: name }));
const guarded = { userId: 510, validateUser: true, fallbackUserId: 9, fallbackRequireAdmin: true, decisionReason: "customer_not_found", systemMessage: "Sem cadastro" };
assert.equal(stepConfigValidationError("ASSIGN", guarded), null);
const changed = { ...guarded, userId: 511 };
assert.equal(changed.fallbackUserId, 9);
assert.equal(changed.fallbackRequireAdmin, true);
assert.equal(changed.decisionReason, "customer_not_found");
assert.ok(stepConfigValidationError("ASSIGN", { ...guarded, userId: 9 }));
assert.ok(stepConfigValidationError("ASSIGN", { ...guarded, fallbackUserId: -1 }));
assert.ok(stepConfigValidationError("ASSIGN", { ...guarded, walletId: 3 }));
console.log("Message flow editor configuration tests passed");
